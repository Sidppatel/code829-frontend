import '@testing-library/jest-dom/vitest';

// jsdom doesn't ship ResizeObserver — antd v6 components (rc-table, rc-resize-observer)
// rely on it. Provide a noop shim so tests render without polyfilling per-suite.
if (typeof globalThis.ResizeObserver === 'undefined') {
  globalThis.ResizeObserver = class ResizeObserver {
    observe() {}
    unobserve() {}
    disconnect() {}
  } as unknown as typeof ResizeObserver;
}

// jsdom also lacks matchMedia; antd Grid (`useBreakpoint`) calls it on mount.
if (typeof window !== 'undefined' && typeof window.matchMedia === 'undefined') {
  Object.defineProperty(window, 'matchMedia', {
    writable: true,
    configurable: true,
    value: (query: string) => ({
      matches: false,
      media: query,
      onchange: null,
      addListener: () => {},
      removeListener: () => {},
      addEventListener: () => {},
      removeEventListener: () => {},
      dispatchEvent: () => false,
    }),
  });
}
